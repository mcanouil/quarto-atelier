#!/usr/bin/env bash
#
# Documentation Pre-render Script
# Generates the project variables and the changelog page.
#
# @license MIT License
# @copyright 2026 Mickaël Canouil
# @author Mickaël Canouil
#
# The extension itself cannot be staged here, because Quarto resolves
# extensions before pre-render runs; see sync-extension.sh.
#
# Quarto re-reads the project configuration after pre-render, which is what
# makes a generated variables file work at all.
#
# The version pill reads the metadata of `_atelier-version.yml`, which a
# {{< var >}} shortcode cannot set.
#

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOCS_DIR="$(dirname "${SCRIPT_DIR}")"
ROOT_DIR="$(dirname "${DOCS_DIR}")"

EXTENSION_NAME=""
for extension_dir in "${ROOT_DIR}"/_extensions/*/; do
	[[ -f "${extension_dir}_extension.yml" ]] || continue
	EXTENSION_NAME="$(basename "${extension_dir}")"
	break
done
if [[ -z "${EXTENSION_NAME}" ]]; then
	EXTENSION_NAME="$(basename "${ROOT_DIR}")"
	printf '[pre-render] No extension under _extensions/; naming the page after %s\n' \
		"${EXTENSION_NAME}"
fi

REPO_SLUG="$(sed -n \
	's|^[[:space:]]*repo-url:[[:space:]]*https://github.com/\([^[:space:]]*\)|\1|p' \
	"${DOCS_DIR}/_quarto.yml" | head -n 1)"
REPO_SLUG="${REPO_SLUG%/}"
if [[ -z "${REPO_SLUG}" ]]; then
	REPO_SLUG="$(git -C "${ROOT_DIR}" remote get-url origin 2>/dev/null |
		sed -n 's|.*github\.com[:/]\(.*\)|\1|p' | sed 's|\.git$||')"
fi
if [[ -z "${REPO_SLUG}" ]]; then
	printf '[pre-render] No repo-url in _quarto.yml and no origin remote\n' >&2
	exit 1
fi

MANIFEST="${ROOT_DIR}/_extensions/${EXTENSION_NAME}/_extension.yml"
VERSION=""
if [[ -f "${MANIFEST}" ]]; then
	VERSION="$(sed -n \
		's/^version:[[:space:]]*["'\'']\{0,1\}\([^"'\''[:space:]]*\).*/\1/p' \
		"${MANIFEST}" | head -n 1)"
	if [[ -z "${VERSION}" ]]; then
		printf '[pre-render] No version in %s\n' "${MANIFEST}" >&2
		exit 1
	fi
fi

{
	printf '# Generated by _scripts/pre-render.sh. Do not edit.\n'
	printf 'extension:\n'
	printf '  name: "%s"\n' "${EXTENSION_NAME}"
	printf '  repo: "%s"\n' "${REPO_SLUG}"
	if [[ -n "${VERSION}" ]]; then
		printf '  version: "%s"\n' "${VERSION}"
		printf '  reference: "%s@%s"\n' "${REPO_SLUG}" "${VERSION}"
		printf '  wizard-reference: "%s%%40%s"\n' "${REPO_SLUG//\//%2F}" "${VERSION}"
	fi
} >"${DOCS_DIR}/_variables.yml"

if [[ -z "${VERSION}" ]]; then
	printf '[pre-render] No %s; the pages have no version to install\n' \
		"${MANIFEST}" >&2
elif ! git -C "${ROOT_DIR}" rev-parse -q --verify "refs/tags/${VERSION}" >/dev/null; then
	printf '[pre-render] warning: %s is not tagged; the install commands name an unreleased version\n' \
		"${VERSION}" >&2
fi

printf '[pre-render] _extension.yml -> _variables.yml (%s@%s)\n' \
	"${REPO_SLUG}" "${VERSION}"

if [[ -n "${VERSION}" ]]; then
	{
		printf '# Generated by _scripts/pre-render.sh. Do not edit.\n'
		printf 'extensions:\n'
		printf '  atelier:\n'
		printf '    version: "%s"\n' "${VERSION}"
	} >"${DOCS_DIR}/_atelier-version.yml"
	printf '[pre-render] _extension.yml -> _atelier-version.yml (%s)\n' "${VERSION}"
else
	rm -f "${DOCS_DIR}/_atelier-version.yml"
fi

if [[ ! -f "${ROOT_DIR}/CHANGELOG.md" ]]; then
	cat >"${DOCS_DIR}/changelog.qmd" <<'EOF'
---
title: "Changelog"
description: "No changelog is available for this extension."
---

No changelog available.
EOF
	printf '[pre-render] No CHANGELOG.md; wrote a placeholder changelog.qmd\n'
	exit 0
fi

awk -v name="${EXTENSION_NAME}" '
BEGIN {
  in_unreleased = 0
  in_version    = 0
  cur_major     = -1
  cur_minor     = -1
  prev_blank    = 1
  printf "---\ntitle: \"Changelog\"\nsubtitle: \"What changed, and when.\"\n"
  printf "description: \"Every released version of the %s extension, and what each one changed.\"\n---\n\n", name
}

function emit(line,    is_blank) {
  is_blank = (line == "")
  if (is_blank) {
    if (!prev_blank) { print ""; prev_blank = 1 }
  } else {
    print line
    prev_blank = 0
  }
}

/^# /             { next }
/^## Unreleased$/ { in_unreleased = 1; next }

in_unreleased && !/^## [0-9]/ { next }
in_unreleased                  { in_unreleased = 0 }

/^## [0-9]+\.[0-9]+\.[0-9]+ \(/ {
  ver   = $2
  date  = substr($3, 2, length($3) - 2)
  split(ver, v, ".")
  major = int(v[1])
  minor = int(v[2])
  patch = int(v[3])

  if (major != cur_major) {
    emit("")
    emit("## " major " {#version-" major "}")
    emit("")
    cur_major = major
    cur_minor = -1
  }

  if (minor != cur_minor) {
    emit("### " major "." minor " {#version-" major "-" minor "}")
    emit("")
    cur_minor = minor
  }

  emit("#### " major "." minor "." patch " (" date ") " \
       "{#version-" major "-" minor "-" patch "}")
  in_version = 1
  next
}

in_version && /^#+ / {
  if (length($1) + 2 > 6) {
    printf "[pre-render] heading too deep to nest: %s\n", $0 > "/dev/stderr"
    emit($0)
  } else {
    emit("##" $0)
  }
  next
}

# A changelog entry naming one of the shortcodes the extension provides, as
# `{{< bam >}}`, is expanded by Quarto rather than shown. The site is not
# rendered by that format, so the expansion fails the render outright.
# Escaping to the Quarto literal form leaves the text visible.
function escape_shortcodes(line) {
  gsub(/{{{</, "\001", line)
  gsub(/>}}}/, "\002", line)
  gsub(/{{</, "{{{<", line)
  gsub(/>}}/, ">}}}", line)
  gsub(/\001/, "{{{<", line)
  gsub(/\002/, ">}}}", line)
  return line
}

{ emit(escape_shortcodes($0)) }
' "${ROOT_DIR}/CHANGELOG.md" >"${DOCS_DIR}/changelog.qmd"

printf '[pre-render] CHANGELOG.md -> changelog.qmd\n'
